"""Export Tiny Safety Model v0 as firmware-friendly C constants."""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import sys
from typing import Any, Mapping

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[3]))


REPO_ROOT = Path(__file__).resolve().parents[3]
DEFAULT_MODEL_ROOT = REPO_ROOT / "model_artifacts" / "tiny_safety_model"
SUMMARY_JSON = "tiny_safety_model_export.json"
SUMMARY_MARKDOWN = "tiny_safety_model_export.md"
HEADER = "tiny_safety_model.h"
TEST_VECTORS = "tiny_safety_test_vectors.json"
SHA256 = "sha256.txt"


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def as_dict(value: Any) -> dict[str, Any]:
    return value if isinstance(value, dict) else {}


def load_json(path: Path) -> dict[str, Any]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict):
        raise ValueError(f"JSON must be an object: {path}")
    return payload


def relative_path(path: Path) -> str:
    resolved = path.resolve()
    try:
        return resolved.relative_to(REPO_ROOT.resolve()).as_posix()
    except (OSError, ValueError):
        return path.name


def latest_artifact(root: Path) -> Path | None:
    if not root.is_dir():
        return None
    artifacts = [path for path in root.glob("**/tiny_safety_model.json") if path.is_file()]
    return sorted(artifacts, key=lambda path: path.stat().st_mtime, reverse=True)[0] if artifacts else None


def c_identifier(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", value).upper()


def c_float(value: Any) -> str:
    return f"{float(value):.6f}f"


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render_header(artifact: Mapping[str, Any]) -> str:
    linear = as_dict(artifact.get("linear_model"))
    feature_names = [str(item) for item in linear.get("feature_names") or []]
    labels = [str(item) for item in linear.get("state_labels") or []]
    weights = linear.get("weights") or []
    biases = linear.get("biases") or []
    test_vectors = artifact.get("test_vectors") if isinstance(artifact.get("test_vectors"), list) else []
    if not feature_names or not labels or len(weights) != len(labels) or len(biases) != len(labels):
        raise ValueError("tiny safety model artifact is missing linear model constants")

    guard = f"EGO_{c_identifier(str(artifact.get('model_id') or 'TINY_SAFETY_MODEL'))}_H"
    lines = [
        "/* Auto-generated by export_tiny_safety_model.py. Do not edit manually. */",
        "/* Synthetic dry-run constants only; firmware integration must be validated separately. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stdint.h>",
        "",
        f"#define EGO_TINY_SAFETY_MODEL_ID {c_string(str(artifact.get('model_id')))}",
        f"#define EGO_TINY_SAFETY_MODEL_VERSION {c_string(str(artifact.get('model_version')))}",
        f"#define EGO_TINY_SAFETY_FEATURE_COUNT ({len(feature_names)})",
        f"#define EGO_TINY_SAFETY_CLASS_COUNT ({len(labels)})",
        f"#define EGO_TINY_SAFETY_TEST_VECTOR_COUNT ({len(test_vectors)})",
        "",
        "static const char *const ego_tiny_safety_feature_names[EGO_TINY_SAFETY_FEATURE_COUNT] = {",
    ]
    lines.extend(f"    {c_string(name)}," for name in feature_names)
    lines += [
        "};",
        "",
        "static const char *const ego_tiny_safety_state_labels[EGO_TINY_SAFETY_CLASS_COUNT] = {",
    ]
    lines.extend(f"    {c_string(label)}," for label in labels)
    lines += [
        "};",
        "",
        "static const float ego_tiny_safety_weights[EGO_TINY_SAFETY_CLASS_COUNT][EGO_TINY_SAFETY_FEATURE_COUNT] = {",
    ]
    for row in weights:
        lines.append("    {" + ", ".join(c_float(value) for value in row) + "},")
    lines += [
        "};",
        "",
        "static const float ego_tiny_safety_biases[EGO_TINY_SAFETY_CLASS_COUNT] = {",
        "    " + ", ".join(c_float(value) for value in biases),
        "};",
        "",
        "static const float ego_tiny_safety_test_features[EGO_TINY_SAFETY_TEST_VECTOR_COUNT][EGO_TINY_SAFETY_FEATURE_COUNT] = {",
    ]
    for vector in test_vectors:
        lines.append("    {" + ", ".join(c_float(value) for value in vector["features"]) + "},")
    label_index = {label: index for index, label in enumerate(labels)}
    lines += [
        "};",
        "",
        "static const uint8_t ego_tiny_safety_test_expected[EGO_TINY_SAFETY_TEST_VECTOR_COUNT] = {",
        "    " + ", ".join(str(label_index[str(vector["expected_label"])]) for vector in test_vectors),
        "};",
        "",
        f"#endif /* {guard} */",
        "",
    ]
    return "\n".join(lines)


def render_markdown(report: Mapping[str, Any]) -> str:
    lines = [
        "# Tiny Safety Model Export",
        "",
        f"- Model ID: `{report['model_id']}`",
        f"- Exported at: `{report['exported_at']}`",
        f"- Header: `{report['paths']['c_header']}`",
        f"- Test vectors: `{report['paths']['test_vectors_json']}`",
        f"- Firmware integrated: `{report['deployment']['firmware_integrated']}`",
        f"- Device deployed: `{report['deployment']['device_deployed']}`",
        "",
        "## Non-Claims",
        "",
    ]
    lines.extend(f"- {item}" for item in report["non_claims"])
    lines.append("")
    return "\n".join(lines)


def write_json(path: Path, payload: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")


def write_sha256(path: Path, files: list[Path]) -> None:
    lines = []
    for file_path in files:
        digest = hashlib.sha256(file_path.read_bytes()).hexdigest()
        lines.append(f"{digest}  {file_path.name}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def export_artifact(
    *,
    model_artifact: Path,
    output_dir: Path,
    exported_at: str,
) -> dict[str, Any]:
    artifact = load_json(model_artifact)
    header_path = output_dir / HEADER
    vector_path = output_dir / TEST_VECTORS
    summary_path = output_dir / SUMMARY_JSON
    markdown_path = output_dir / SUMMARY_MARKDOWN
    sha_path = output_dir / SHA256
    output_dir.mkdir(parents=True, exist_ok=True)
    header_path.write_text(render_header(artifact), encoding="utf-8", newline="\n")
    write_json(
        vector_path,
        {
            "model_id": artifact.get("model_id"),
            "model_version": artifact.get("model_version"),
            "feature_names": as_dict(artifact.get("linear_model")).get("feature_names"),
            "state_labels": as_dict(artifact.get("linear_model")).get("state_labels"),
            "test_vectors": artifact.get("test_vectors"),
            "synthetic_only": True,
        },
    )
    report = {
        "schema_version": "egolink.tiny_safety_model_export.v0.1",
        "model_id": artifact.get("model_id"),
        "model_version": artifact.get("model_version"),
        "exported_at": exported_at,
        "source_artifact": relative_path(model_artifact),
        "paths": {
            "export_report_json": relative_path(summary_path),
            "export_report_markdown": relative_path(markdown_path),
            "c_header": relative_path(header_path),
            "test_vectors_json": relative_path(vector_path),
            "sha256": relative_path(sha_path),
        },
        "deployment": {
            "firmware_integrated": False,
            "device_deployed": False,
            "measured_latency_ms": None,
            "measured_ram_bytes": None,
            "measured_flash_bytes": None,
            "measured_power_mw": None,
        },
        "scope": {
            "synthetic_only": True,
            "firmware_changed": False,
            "hardware_contacted": False,
            "device_deployed": False,
            "model_training_started": False,
        },
        "non_claims": [
            "C header export only; no firmware integration is performed.",
            "Synthetic integration model only; no real-world accuracy is claimed.",
            "No latency, RAM, flash, or power measurement is claimed.",
        ],
    }
    write_json(summary_path, report)
    markdown_path.write_text(render_markdown(report), encoding="utf-8")
    write_sha256(sha_path, [summary_path, markdown_path, header_path, vector_path])
    return report


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model-artifact", type=Path)
    parser.add_argument("--model-root", type=Path, default=DEFAULT_MODEL_ROOT)
    parser.add_argument("--output-dir", type=Path)
    parser.add_argument("--exported-at")
    parser.add_argument("--json", action="store_true")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    artifact = args.model_artifact or latest_artifact(args.model_root)
    if artifact is None:
        message = f"tiny safety model artifact not found under {args.model_root}"
        if args.json:
            print(json.dumps({"ok": False, "error": message}, indent=2, sort_keys=True))
        else:
            print(f"ERROR: {message}", file=sys.stderr)
        return 2
    output_dir = args.output_dir or artifact.parent / "export"
    report = export_artifact(
        model_artifact=artifact,
        output_dir=output_dir,
        exported_at=args.exported_at or utc_now(),
    )
    if args.json:
        print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))
    else:
        print(f"PASS tiny safety model export: {report['paths']['c_header']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
